def to_html(md_text: str) -> str:
    import markdown
    html_body = markdown.markdown(
        md_text, extensions=["tables", "fenced_code", "sane_lists", "attr_list"])
    return (f"<!doctype html><html><head><meta charset='utf-8'>"
            f"<title>{TITLE}</title><style>{CSS}</style></head>"
            f"<body>{html_body}</body></html>")


def find_browser() -> str:
    for candidate in (
        shutil.which("chrome"), shutil.which("msedge"),
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
        r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
        r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
        "/usr/bin/google-chrome", "/usr/bin/chromium",
    ):
        if candidate and os.path.exists(candidate):
            return candidate
    return ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="validate citations and figure anchors, write nothing")
    ap.add_argument("--no-pdf", action="store_true", help="skip the browser step")
    args = ap.parse_args()

    result = build(check_only=args.check)
    if isinstance(result, int):
        return result
    md = result

    html = to_html(md)
    with open(OUT_STEM + ".html", "w", encoding="utf-8") as fh:
        fh.write(html)
    print(f"wrote {os.path.relpath(OUT_STEM + '.html', REPO)}")

    if args.no_pdf:
        return 0
    browser = find_browser()
    if not browser:
        print("no Chrome/Edge found; skipping PDF. HTML is complete "
              "(open it and print to PDF).")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [browser, "--headless", "--disable-gpu", "--no-sandbox",
               f"--user-data-dir={tmp}", "--no-pdf-header-footer",
               f"--print-to-pdf={OUT_STEM + '.pdf'}",
               "file:///" + (OUT_STEM + ".html").replace("\\", "/")]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
    if os.path.exists(OUT_STEM + ".pdf"):
        size = os.path.getsize(OUT_STEM + ".pdf")
        print(f"wrote {os.path.relpath(OUT_STEM + '.pdf', REPO)} ({size:,} bytes)")
        return 0
    print("PDF was not produced. Browser said:")
    print((proc.stderr or proc.stdout or "")[-800:])
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
