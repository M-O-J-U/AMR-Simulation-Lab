"""Assemble the drafted sections into one standalone document (Markdown, HTML, PDF).

There is no venue for this version, so the output is a self-contained report rather
than a conference/journal submission package: no IEEE template, no LaTeX.

What it does
------------
1. Reads `paper/draft/*.md` in filename order and strips the drafting comments.
2. Resolves `[bibkey]` and `[key1; key2]` markers into numbered citations, in order
   of first appearance, against `paper/refs.bib`. Every marker must resolve; an
   unknown key is a hard error, so a typo cannot silently vanish from the text.
3. Inserts the figures from `paper/figures/` at the end of their anchor sections,
   with the captions generated by `paper/make_figures.py`.
4. Emits a References list containing only works actually cited, plus a
   "Citation notes" appendix recording, per reference, how far it was verified --
   full text, abstract only, or publisher/preprint page. Abstract-only sources are
   listed explicitly rather than left implicit.
5. Renders to HTML and then to PDF via headless Chrome or Edge, if one is present.

Usage
-----
    python paper/assemble.py                # Markdown + HTML + PDF
    python paper/assemble.py --no-pdf       # skip the browser step
    python paper/assemble.py --check        # validate citations/anchors, write nothing

Outputs `paper/amr_hgt_gnn.{md,html,pdf}`.

Build-time dependencies, deliberately NOT added to requirements.txt (that file pins the
runtime environment the results were generated on, and nothing here touches the
pipeline): the `markdown` package for HTML rendering, and Chrome or Edge for the PDF.
Without either, the Markdown is still written and `--no-pdf` skips the browser step.
"""

