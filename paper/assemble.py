def read_sections() -> list:
    out = []
    for name in sorted(os.listdir(DRAFT)):
        if not name.endswith(".md"):
            continue
        with open(os.path.join(DRAFT, name), encoding="utf-8") as fh:
            body = fh.read()
        body = re.sub(r"<!--.*?-->", "", body, flags=re.S).strip()
        out.append((name, body))
    return out


def parse_bib(path: str) -> dict:
    with open(path, encoding="utf-8") as fh:
        raw = fh.read()
    entries = {}
    for match in re.finditer(r"@(\w+)\{([^,]+),(.*?)\n\}", raw, flags=re.S):
        kind, key, body = match.group(1), match.group(2).strip(), match.group(3)
        fields = {}
        for fm in re.finditer(r"(\w+)\s*=\s*\{(.*?)\}\s*,?\s*(?=\n\s*\w+\s*=|\s*$)",
                              body, flags=re.S):
            fields[fm.group(1).lower()] = " ".join(fm.group(2).split())
        entries[key] = {"kind": kind, **fields}
    return entries


def tidy(value: str) -> str:
    """Strip the LaTeX-isms our .bib uses for a plain-text/HTML rendering."""
    value = value.replace("--", "\u2013")
    value = re.sub(r"\{\\['`\"^~=.]\{?(\w)\}?\}", r"\1", value)
    value = re.sub(r"\\['`\"^~=.]\{?(\w)\}?", r"\1", value)
    value = value.replace("{\\v{c}}", "c").replace("{\\'c}", "c")
    value = value.replace("$\\beta$", "\u03b2").replace("\\&", "&")
    return value.replace("{", "").replace("}", "")


def format_reference(key: str, e: dict) -> str:
    authors = tidy(e.get("author", "")).replace(" and ", "; ")
    title = tidy(e.get("title", ""))
    year = e.get("year", "n.d.")
    if e["kind"].lower() == "inproceedings":
        venue = tidy(e.get("booktitle", ""))
        tail = f"{venue}, {year}."
        if e.get("eprint"):
            tail += f" arXiv:{e['eprint']}."
    else:
        venue = tidy(e.get("journal", ""))
        bits = [venue]
        if e.get("volume"):
            v = e["volume"] + (f"({e['number']})" if e.get("number") else "")
            bits.append(v)
        if e.get("pages"):
            bits.append(tidy(e["pages"]))
        tail = f"{', '.join(b for b in bits if b)}, {year}."
    sep = "" if authors.endswith(".") else "."
    out = f"{authors}{sep} {title}. {tail}"
    if e.get("doi"):
        out += f" doi:{e['doi']}"
    if e.get("note"):
        out += f" ({tidy(e['note'])})"
    return out


def resolve_citations(text: str, bib: dict) -> tuple:
    """Replace [key] / [key1; key2] with numbered citations, in first-use order."""
    keys = sorted(bib, key=len, reverse=True)
    pattern = re.compile(
        r"\[((?:" + "|".join(re.escape(k) for k in keys) + r")"
        r"(?:\s*;\s*(?:" + "|".join(re.escape(k) for k in keys) + r"))*)\]")
    order: list = []
    problems: list = []

    def repl(m):
        cited = [c.strip() for c in m.group(1).split(";")]
        nums = []
        for c in cited:
            if c not in bib:
                problems.append(f"unknown citation key: {c}")
                continue
            if c not in order:
                order.append(c)
            nums.append(order.index(c) + 1)
        return "[" + ", ".join(str(n) for n in nums) + "]"

    text = pattern.sub(repl, text)

    # Any surviving bracketed token that looks like a bibkey is a typo.
    for stray in re.finditer(r"\[([a-z][a-z0-9]*\d{4}[a-z0-9]*)\]", text):
        problems.append(f"unresolved citation marker: [{stray.group(1)}]")
    return text, order, problems


def load_captions() -> dict:
    """Map figure stem -> (title, caption body) from paper/figures/captions.md."""
    path = os.path.join(FIGDIR, "captions.md")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        raw = fh.read()
    out = {}
    blocks = re.split(r"<!--\s*fig:\s*(\S+?)\s*-->", raw)
    # blocks = [preamble, stem1, body1, stem2, body2, ...]
    for stem, body in zip(blocks[1::2], blocks[2::2]):
        body = body.strip()
        heading, _, rest = body.partition("\n")
        title = heading.lstrip("# ").strip()
        rest = re.split(r"\n<!--", rest)[0]
        out[stem] = (title, " ".join(rest.split()))
    return out


def insert_figures(text: str) -> tuple:
    problems = []
    caps = load_captions()
    for number, (stem, anchor) in enumerate(FIGURES, 1):
        label = f"Figure {number}"
        if anchor not in text:
            problems.append(f"figure anchor not found: {anchor!r} (for {stem})")
            continue
        png = os.path.join(FIGDIR, stem + ".png")
        if not os.path.exists(png):
            problems.append(f"missing figure file: {stem}.png "
                            "(run python paper/make_figures.py)")
            continue
        start = text.index(anchor)
        nxt = text.find("\n## ", start + len(anchor))
        nxt2 = text.find("\n# ", start + len(anchor))
        if nxt == -1 or (nxt2 != -1 and nxt2 < nxt):
            nxt = nxt2
        if nxt == -1:
            nxt = len(text)
        if stem not in caps:
            problems.append(f"no caption for {stem} in figures/captions.md "
                            "(is its <!-- fig: --> marker present?)")
            continue
        title, caption = caps[stem]
        block = (f"\n\n![{label}: {title}](figures/{stem}.png)\n\n"
                 f"**{label}. {title}.** {caption}\n")
        text = text[:nxt] + block + text[nxt:]
    return text, problems



def build(check_only: bool = False) -> int:
    bib = parse_bib(BIB)
    problems = [f"refs.bib key missing a verification level: {k}"
                for k in bib if k not in VERIFICATION]
    problems += [f"VERIFICATION lists a key not in refs.bib: {k}"
                 for k in VERIFICATION if k not in bib]

    sections = read_sections()
    body = "\n\n".join(text for _name, text in sections)

    body, fig_problems = insert_figures(body)
    problems += fig_problems

    body, order, cite_problems = resolve_citations(body, bib)
    problems += cite_problems

    if problems:
        print("FAILED:")
        for p in problems:
            print("  - " + p)
        return 1
    print(f"sections: {len(sections)}  citations resolved: {len(order)}  "
          f"figures: {len(FIGURES)}")

    today = datetime.date.today().isoformat()
    head = (f"# {TITLE}\n\n**{SUBTITLE}**  \n"
            f"Assembled {today} by `paper/assemble.py` from `paper/draft/`.  \n"
            "Every number is traceable to `paper/claims_to_numbers.md`; figures are "
            "regenerated from committed result files by `paper/make_figures.py`.\n\n"
            "---\n")

    refs = ["\n\n# References\n"]
    for i, key in enumerate(order, 1):
        refs.append(f"{i}. {format_reference(key, bib[key])}")
    refs_text = "\n".join(refs)

    abstract_only = [k for k in order if VERIFICATION[k].startswith("abstract")]
    notes = [
        "\n\n# Appendix A. Citation notes\n",
        "Every reference above was checked against the source itself, not merely "
        "confirmed to exist: author list, venue, year and DOI, and whether the source "
        "actually supports the claim it is cited for. The audit is recorded in "
        "`paper/citations.md` and, for gene transfer mechanisms, in "
        "`paper/gene_mechanism_audit.md`.\n",
        "Because this version has no submission deadline, sources whose full text sits "
        "behind a paywall were verified against their abstracts and are cited only for "
        "what those abstracts state. They are listed here so the distinction is on the "
        "record rather than implied.\n",
        "| # | Reference key | Verified against |",
        "|---|---|---|",
    ]
    for i, key in enumerate(order, 1):
        notes.append(f"| {i} | `{key}` | {VERIFICATION[key]} |")
    notes.append(
        f"\n{len(abstract_only)} of the {len(order)} cited sources were verified at "
        "abstract level only. Upgrading them to full text is listed as outstanding work "
        "in `paper/STATUS.md`.\n")
    uncited = sorted(set(bib) - set(order))
    if uncited:
        notes.append(
            "`paper/refs.bib` additionally holds "
            + ", ".join(f"`{k}`" for k in uncited)
            + " — sources verified during the gene-mechanism audit that the text does "
              "not cite. They are kept for that record and are deliberately absent from "
              "the reference list above.\n")

    md = head + body + refs_text + "\n".join(notes)

    if check_only:
        print("check only: no files written")
        return 0

    with open(OUT_STEM + ".md", "w", encoding="utf-8") as fh:
        fh.write(md)
    print(f"wrote {os.path.relpath(OUT_STEM + '.md', REPO)}")
    return md


